import matplotlib; matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle, Circle
s=100
fig,(a,b)=plt.subplots(2,1,figsize=(11,11),gridspec_kw={'height_ratios':[1.3,1]})
def R(ax,x0,x1,y0,y1,fc,ec='k',ls='-',lw=1,al=1,txt=None,fs=8):
    ax.add_patch(Rectangle((x0,y0),x1-x0,y1-y0,fc=fc,ec=ec,ls=ls,lw=lw,alpha=al))
    if txt: ax.text((x0+x1)/2,(y0+y1)/2,txt,ha='center',va='center',fontsize=fs)
a.set_title('Vista en planta (x longitudinal, y lateral), medidas en mm',fontsize=10)
R(a,0,500,0,400,'none','0.3',lw=0.5)
for y0 in (0,380): R(a,0,500,y0,y0+20,'#b0b7c3')
for x0 in (0,480): R(a,x0,x0+20,0,400,'#b0b7c3')
tip=s-27.5   # el travesano termina en la cara interior de la rueda
R(a,40,60,-tip,400+tip,'#8fa0b8'); R(a,480,500,-tip,400+tip,'#8fa0b8')
for xc in (50,490):
    for yc in (-s,400+s): R(a,xc-100,xc+100,yc-27.5,yc+27.5,'#555555',al=0.5)
R(a,90,340,20,120,'#f2c14e',txt='Cubo S\npotencia\n250×100')
R(a,90,340,280,380,'#f2c14e',txt='Cubo S\ncontrol\n250×100')
R(a,150,350,140,260,'#6bb36b',txt='Cubo D batería\n200×120')
R(a,29,71,24,149.5,'#d9534f',txt='42PG',fs=7); R(a,29,71,250.5,376,'#d9534f',txt='42PG',fs=7)
for yc in (-60,460): R(a,470,510,yc-10,yc+10,'#9b59b6',al=0.85,txt='servo',fs=6)
R(a,54,741,80.5,319.5,'none','#1f4e9c',ls='--',lw=1.2)
a.text(560,200,'mecanismo de elevación\n(θ = 15°)',color='#1f4e9c',ha='center',fontsize=8)
a.annotate('',xy=(490,-190),xytext=(50,-190),arrowprops=dict(arrowstyle='<->'));a.text(270,-205,'distancia entre ejes 440',ha='center',fontsize=8)
a.annotate('',xy=(-s,-165),xytext=(400+s,-165),arrowprops=dict(arrowstyle='<->'));a.text(200,-178,'vía 600 (s = 100)',ha='center',fontsize=8)
a.text(50,-s-40,'rueda Ø200 × 55',ha='center',fontsize=7)
a.set_xlim(-130,780);a.set_ylim(-220,560);a.set_aspect('equal');a.invert_yaxis()
b.set_title('Vista lateral (x longitudinal, z vertical), medidas en mm; suelo en z = −59',fontsize=10)
R(b,0,500,0,260,'none','0.3',lw=0.5)
for z0 in (0,240): R(b,0,500,z0,z0+20,'#b0b7c3')
for x0 in (0,480): R(b,x0,x0+20,0,260,'#b0b7c3')
b.axhline(-59,color='k',lw=1.5)
for xc in (50,490): b.add_patch(Circle((xc,41),100,fc='#555555',alpha=0.35,ec='k'))
R(b,90,340,20,195,'#f2c14e',txt='Cubo S (175 de alto)')
R(b,150,350,20,106,'#6bb36b',txt='Cubo D',fs=7)
b.add_patch(Circle((50,41),21,fc='#d9534f',ec='k')); b.text(50,95,'42PG',ha='center',fontsize=7)
R(b,34,74,260,500,'none','#1f4e9c',ls='--'); b.text(150,330,'base de elevación (postes 250 mm)',color='#1f4e9c',fontsize=8)
b.annotate('',xy=(620,-59),xytext=(620,0),arrowprops=dict(arrowstyle='<->')); b.text(630,-35,'despeje 59',fontsize=8)
b.set_xlim(-130,780);b.set_ylim(-90,520);b.set_aspect('equal')
plt.tight_layout(); plt.savefig('../../Recursos/Imagenes/ImagenesDisenoMecanico/ESTRUCTURA_DISTRIBUCION.png',dpi=150)
